// Map content type to pixel icon component
export function PixelIcon({ contentType, size = 48 }: { contentType: string; size?: number }) {
  switch (contentType) {
    case "about":
      return <PixelAboutIcon size={size} />;
    case "projects":
      return <PixelProjectsIcon size={size} />;
    case "blog":
      return <PixelBlogIcon size={size} />;
    case "cv":
      return <PixelCVIcon size={size} />;
    default:
      return <PixelProjectsIcon size={size} />;
  }
}
